// Wraps game/index.html in a full HTML document and writes it to src/game-html.ts,
// so the app can load the game into a WebView without asset loading.
// Run after editing the game: npm run build:game
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const body = fs.readFileSync(path.join(root, 'game', 'index.html'), 'utf8');

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover">
</head>
<body>
${body}
</body>
</html>
`;

fs.mkdirSync(path.join(root, 'dist-web'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist-web', 'index.html'), html);

const ts = `// Generated by scripts/build-game.js from game/index.html. Do not edit by hand.
export const GAME_HTML = ${JSON.stringify(html)};
`;
fs.writeFileSync(path.join(root, 'src', 'game-html.ts'), ts);
console.log(`Built game: ${(html.length / 1024).toFixed(1)} KB -> src/game-html.ts and dist-web/index.html`);
